"""Staging area for agent-made scenes: check → stage → promote (or remove).

    report = await check_draft("HuffmanTreeScene", draft_path, job_dir, request)   # all checks, nothing published
    await publish("HuffmanTreeScene", draft_path, job_dir, request)                # only when the agent finishes
    await promote("HuffmanTreeScene")      # src/staging/ → src/scenes/ + registry.ts
    await unstage("HuffmanTreeScene")      # remove a staged scene

A draft only enters ``rendering/src/staging/`` while it is being checked and is always taken out
again afterwards. It goes live only through ``publish`` (called by the agent's ``finish``), so a
run that stops early never leaves a half-reviewed scene behind. Passed scenes are listed in
``staging/manifest.json`` and registered through the generated ``staging/index.ts``; the scene
catalog (library/registry.json) is regenerated so the planner can use them right away.
"""

import asyncio
import json
import logging
import re
import shutil
import time
from dataclasses import dataclass, field
from pathlib import Path

from app.config import settings
from app.utils.render import _run

log = logging.getLogger(__name__)

LOCK = asyncio.Lock()  # one staging change at a time

ALLOWED_IMPORTS = re.compile(
    r"^(react|remotion|zod|three|three/examples/jsm/.+|@react-three/fiber|@remotion/(three|shapes|paths|transitions|transitions/.+|media-utils)|lucide-react|\.\./.+|\./.+)$"
)
FORBIDDEN = [
    (r"Math\.random\s*\(", "Math.random() (renders must be deterministic; use a seeded value or the frame)"),
    (r"Date\.now\s*\(|new Date\s*\(", "the clock (use useCurrentFrame())"),
    (r"\b(setTimeout|setInterval|requestAnimationFrame)\s*\(", "timers (animate from useCurrentFrame())"),
    (r"\bfetch\s*\(|XMLHttpRequest|WebSocket", "network access"),
    (r"\b(localStorage|sessionStorage|document\.cookie)\b", "browser storage"),
    (r"\beval\s*\(|new Function\s*\(", "eval"),
    (r"\bprocess\.env\b", "environment variables"),
    (r"<(iframe|script)\b", "<iframe>/<script>"),
]
NAME = re.compile(r"^[A-Z][A-Za-z0-9]{2,40}Scene$")


@dataclass
class CheckReport:
    ok: bool
    name: str
    steps: list[str] = field(default_factory=list)
    errors: str = ""
    stills: list[Path] = field(default_factory=list)

    def text(self) -> str:
        head = "ALL CHECKS PASSED" if self.ok else "CHECK FAILED"
        return f"{head}: {self.name}\n" + "\n".join(self.steps) + (f"\n\nErrors:\n{self.errors}" if self.errors else "")


def _staging() -> Path:
    return settings.RENDERING_DIR / "src" / "staging"


def _manifest_path() -> Path:
    return _staging() / "manifest.json"


def manifest() -> dict:
    p = _manifest_path()
    return json.loads(p.read_text()) if p.exists() else {"components": {}}


def _save_manifest(m: dict) -> None:
    _manifest_path().write_text(json.dumps(m, indent=2) + "\n")


def _write_index(names: list[str]) -> None:
    lines = [
        "// AUTO-GENERATED by the backend component agent (app/agent). Do not edit by hand.",
        "// Staged scenes: written by the agent, passed every check, waiting to be promoted to src/scenes/.",
        "import type {SceneEntry} from '../registry';",
    ]
    lines += [f"import * as {n} from './{n}';" for n in names]
    lines.append("")
    lines.append("export const stagingCatalog: Record<string, SceneEntry> = {")
    lines += [f"  {n}: {{description: {n}.description, tags: {n}.tags, component: {n}.{n}, schema: {n}.schema}}," for n in names]
    lines.append("};")
    (_staging() / "index.ts").write_text("\n".join(lines) + "\n")


def staged_names() -> list[str]:
    return sorted(manifest()["components"])


def existing_scene_names() -> set[str]:
    try:
        return {e["name"] for e in json.loads((settings.RENDERING_DIR.parent / "library" / "registry.json").read_text())}
    except FileNotFoundError:
        return set()


def static_check(source: str) -> list[str]:
    """Rule check without running anything: imports and forbidden APIs."""
    problems = []
    for m in re.finditer(r"""^\s*import\s+(?:[^'"]+\s+from\s+)?['"]([^'"]+)['"]""", source, re.M):
        mod = m.group(1)
        if not ALLOWED_IMPORTS.match(mod):
            problems.append(f"import '{mod}' is not allowed (allowed: react, remotion, zod, three, @react-three/fiber, @remotion/*, lucide-react, relative '../' project files)")
        if mod.startswith("../") and mod.split("/")[1] in {"staging"}:
            problems.append(f"import '{mod}': don't import other staged scenes")
    for rx, what in FORBIDDEN:
        if re.search(rx, source):
            problems.append(f"uses {what}")
    if not re.search(r"export\s+const\s+schema\s*=", source):
        problems.append("missing `export const schema = z.object({...})`")
    if not re.search(r"export\s+const\s+description\s*=", source):
        problems.append("missing `export const description = '...'`")
    if not re.search(r"export\s+const\s+tags\s*=", source):
        problems.append("missing `export const tags = [...]`")
    return problems


async def _tsc() -> str:
    code, out = await _run(["npx", "tsc", "--noEmit"], timeout=300)
    return "" if code == 0 else "\n".join(out.strip().splitlines()[:60])


async def _scene_contract(name: str) -> tuple[str, dict]:
    """Bundle the registry in Node: the scene is registered, has metadata, and parse({}) works."""
    script = (
        "import {build} from 'esbuild'; import path from 'node:path'; import {pathToFileURL} from 'node:url';"
        "const root=process.cwd(); const out=path.join(root,'out','agent-contract.mjs');"
        "await build({stdin:{contents:`export {sceneCatalog} from './src/registry';`,resolveDir:root,loader:'ts'},outfile:out,bundle:true,platform:'node',format:'esm',packages:'external',loader:{'.css':'empty'},"
        "plugins:[{name:'w',setup(b){b.onResolve({filter:/^world-atlas\\//},(a)=>({path:path.join(root,'node_modules',a.path),external:false}))}}],logLevel:'silent'});"
        "const {sceneCatalog}=await import(pathToFileURL(out)); const e=sceneCatalog[process.argv[1]];"
        "if(!e){console.log('NOT_REGISTERED');process.exit(1)}"
        "if(!e.description||!Array.isArray(e.tags)||!e.tags.length){console.log('description and tags are required');process.exit(1)}"
        "const r=e.schema.safeParse({}); if(!r.success){console.log('schema.parse({}) fails (every field needs a default or must be optional): '+r.error.message);process.exit(1)}"
        "console.log('DEFAULTS '+JSON.stringify(r.data));"
    )
    code, out = await _run(["node", "--input-type=module", "-e", script, name], timeout=180)
    if code != 0:
        return out.strip()[-3000:], {}
    m = re.search(r"^DEFAULTS (.*)$", out, re.M)
    return "", json.loads(m.group(1)) if m else {}


async def _stills(name: str, job_dir: Path, duration: int = 150) -> tuple[str, list[Path]]:
    """Render first / middle / last frames of the scene with its default props."""
    comp = {"fps": 30, "width": 1920, "height": 1080, "defaultTransition": {"type": "none"}, "audio": {"effects": False},
            "scenes": [{"id": "check", "component": name, "durationInFrames": duration, "props": {}}]}
    props = job_dir / "check-composition.json"
    props.write_text(json.dumps(comp))
    bundle = job_dir / "bundle"
    code, out = await _run(["npx", "remotion", "bundle", "src/index.ts", f"--out-dir={bundle}"], timeout=300)
    if code != 0:
        return "bundle failed:\n" + out[-2500:], []
    paths = []
    try:
        for frame in (10, duration // 2, duration - 1):
            png = job_dir / f"still-{frame}.png"
            code, out = await _run(["npx", "remotion", "still", str(bundle), "VideoComposition", str(png), f"--props={props}",
                                    f"--frame={frame}", "--scale=0.5", "--gl=angle"], timeout=300)
            if code != 0 or not png.exists():
                lines = [l for l in out.splitlines() if "Deprecation" not in l and "require(" not in l]
                return f"render of frame {frame} failed:\n" + "\n".join(lines)[-2500:], paths
            paths.append(png)
    finally:
        shutil.rmtree(bundle, ignore_errors=True)
    return "", paths


async def check_draft(name: str, draft: Path, job_dir: Path, request: str) -> CheckReport:
    """Run every check on a draft WITHOUT publishing it.

    The draft is installed in ``src/staging/`` only while typecheck / contract / render run, then the
    staging area is put back exactly as it was, pass or fail. Publishing happens in ``publish``.
    """
    report = CheckReport(False, name)
    if not NAME.match(name):
        report.errors = "name must be PascalCase and end with 'Scene', e.g. HuffmanTreeScene"
        return report
    if not draft.is_file():
        report.errors = f"draft not found: write it first to {draft.name} in your draft folder"
        return report
    if name in existing_scene_names() and name not in staged_names():
        report.errors = f"{name} already exists in the library; pick another name"
        return report
    source = draft.read_text()
    if not re.search(rf"export\s+const\s+{name}\b", source):
        report.errors = f"the component must be exported as `export const {name}: React.FC<...> = ...`"
        return report
    problems = static_check(source)
    report.steps.append("1. rules (imports, no randomness/clock/timers/network): " + ("ok" if not problems else "FAILED"))
    if problems:
        report.errors = "\n".join(f"- {p}" for p in problems)
        return report

    async with LOCK:
        target = _staging() / f"{name}.tsx"
        backup = target.read_text() if target.exists() else None
        shutil.copyfile(draft, target)
        _write_index(sorted(set(staged_names()) | {name}))
        try:
            errs = await _tsc()
            report.steps.append("2. typecheck: " + ("ok" if not errs else "FAILED"))
            if errs:
                report.errors = errs
                return report
            errs, defaults = await _scene_contract(name)
            report.steps.append("3. contract (registered, description/tags, all props have defaults): " + ("ok" if not errs else "FAILED"))
            if errs:
                report.errors = errs
                return report
            errs, stills = await _stills(name, job_dir)
            report.stills = stills
            report.steps.append("4. render first/middle/last frame: " + ("ok" if not errs else "FAILED"))
            if errs:
                report.errors = errs
                return report
            report.steps.append(f"   default props: {json.dumps(defaults)[:600]}")
            report.steps.append("   not published yet: look at the frames, then call finish to publish it")
            report.ok = True
            return report
        finally:
            # always put the staging area back exactly as it was
            if backup is None:
                target.unlink(missing_ok=True)
            else:
                target.write_text(backup)
            _write_index(staged_names())


async def publish(name: str, draft: Path, job_dir: Path, request: str) -> str:
    """Make a checked draft live: staging file + manifest + index + scene catalog, all or nothing.

    Re-runs the fast checks (typecheck, contract) because other scenes may have changed since the
    draft was checked. Raises RuntimeError (with everything rolled back) if anything fails.
    """
    async with LOCK:
        target = _staging() / f"{name}.tsx"
        old_file = target.read_text() if target.exists() else None
        old_manifest = manifest()
        catalog_touched = False
        try:
            shutil.copyfile(draft, target)
            _write_index(sorted(set(staged_names()) | {name}))
            errs = await _tsc()
            if errs:
                raise RuntimeError(f"typecheck failed at publish:\n{errs}")
            errs, _ = await _scene_contract(name)
            if errs:
                raise RuntimeError(f"contract failed at publish:\n{errs}")
            m = manifest()
            m["components"][name] = {"request": request, "job": job_dir.name, "staged_at": time.strftime("%Y-%m-%dT%H:%M:%S")}
            _save_manifest(m)
            _write_index(staged_names())
            catalog_touched = True
            code, out = await _run(["npm", "run", "-s", "check:scenes"], timeout=300)
            if code != 0:
                raise RuntimeError(f"scene catalog update failed:\n{out[-2000:]}")
            return f"published {name}: usable in videos and visible to the planner (staged; promote to keep it)"
        except Exception:
            if old_file is None:
                target.unlink(missing_ok=True)
            else:
                target.write_text(old_file)
            _save_manifest(old_manifest)
            _write_index(staged_names())
            if catalog_touched:
                await _run(["npm", "run", "-s", "check:scenes"], timeout=300)
            raise


async def unstage(name: str) -> None:
    async with LOCK:
        m = manifest()
        if name not in m["components"]:
            raise ValueError(f"{name} is not staged")
        (_staging() / f"{name}.tsx").unlink(missing_ok=True)
        del m["components"][name]
        _save_manifest(m)
        _write_index(staged_names())
        await _run(["npm", "run", "-s", "check:scenes"], timeout=300)


async def promote(name: str) -> str:
    """Move a staged scene into src/scenes/ and register it in registry.ts for good."""
    async with LOCK:
        m = manifest()
        if name not in m["components"]:
            raise ValueError(f"{name} is not staged")
        src_dir = settings.RENDERING_DIR / "src"
        staged, final = src_dir / "staging" / f"{name}.tsx", src_dir / "scenes" / f"{name}.tsx"
        if final.exists():
            raise ValueError(f"src/scenes/{name}.tsx already exists")
        registry = src_dir / "registry.ts"
        before = registry.read_text()
        marker = "  // <promoted-scenes>"
        if marker not in before:
            raise RuntimeError("registry.ts has no <promoted-scenes> marker")
        alias = f"Agent{name}"
        text = before.replace("import {stagingCatalog} from './staging';", f"import {{stagingCatalog}} from './staging';\nimport * as {alias} from './scenes/{name}';", 1)
        text = text.replace(marker, f"  {name}: {{description: {alias}.description, tags: {alias}.tags, component: {alias}.{name}, schema: {alias}.schema}},\n{marker}", 1)

        shutil.move(staged, final)  # same folder depth, so '../' imports still work
        entry = m["components"].pop(name)
        _save_manifest(m)
        _write_index(staged_names())
        registry.write_text(text)
        errs = await _tsc()
        code, out = await _run(["npm", "run", "-s", "check:scenes"], timeout=300)
        if errs or code != 0:  # roll back
            shutil.move(final, staged)
            registry.write_text(before)
            m["components"][name] = entry
            _save_manifest(m)
            _write_index(staged_names())
            await _run(["npm", "run", "-s", "check:scenes"], timeout=300)
            raise RuntimeError("promotion failed, rolled back:\n" + (errs or out[-2000:]))
        return f"rendering/src/scenes/{name}.tsx"
